def translate(language: str, key: str, **values: Any) -> str:
    """Return a localized string and fail loudly for missing translation keys."""
    if language not in TRANSLATIONS:
        raise ValueError(f"Unsupported language: {language}")
    try:
        template = TRANSLATIONS[language][key]
    except KeyError as exc:
        raise KeyError(f"Missing translation key '{key}' for language '{language}'.") from exc
    return template.format(**values)
